import AppKit

/// The libghostty configuration Wireline generates from its own settings.
///
/// libghostty has no per-key setter: a config is a Ghostty-syntax file that
/// `ghostty_config_load_file` parses. We never load the user's
/// `~/.config/ghostty` (`load_default_files`) — every value comes from here,
/// so the terminal looks and behaves the same whichever engine draws it.
enum GhosttyConfig {
    /// The config text for `appearance`. `focused: false` is the dimmed
    /// variant (see `GhosttyTerminalView.keepsCaretShapeWhenUnfocused`).
    static func text(for a: TerminalAppearance, focused: Bool = true) -> String {
        var lines: [String] = [
            "# Generated by Wireline — not the user's Ghostty config.",

            // Colours. The background keeps the theme's RGB (OSC 11 answers,
            // faint text and cell blending use it) but paints fully transparent:
            // the app wallpaper sits behind every terminal.
            "background = \(hex(a.theme.background))",
            "foreground = \(hex(a.theme.foreground))",
            "cursor-color = \(hex(a.theme.cursor))",
            "background-opacity = 0",
        ]
        for (i, c) in a.theme.ansi.prefix(16).enumerated() {
            lines.append("palette = \(i)=\(hex(c))")
        }

        // Font. Hidden system families (".AppleSystemUIFontMonospaced") can't
        // be found by name; leaving it out picks Ghostty's built-in font.
        // Nerd Font symbols are built in either way.
        let family = a.font.familyName ?? ""
        if !family.isEmpty, !family.hasPrefix(".") { lines.append("font-family = \(family)") }
        lines.append("font-size = \(clean(a.font.pointSize))")

        // Cursor. Unfocused: the same shape at 35%, steady — like the SwiftTerm view.
        let style = switch a.cursorShape {
        case .block: "block"
        case .bar: "bar"
        case .underline: "underline"
        }
        lines += [
            "cursor-style = \(style)",
            "cursor-style-blink = \(focused && a.cursorBlink)",
            "cursor-opacity = \(focused ? "1" : "0.35")",
        ]

        lines += [
            // Wireline pads around the terminal view itself.
            "window-padding-x = 0",
            "window-padding-y = 0",
            "window-padding-balance = false",
            // Remote hosts rarely have xterm-ghostty's terminfo.
            "term = xterm-256color",
            // Wireline injects its own zsh integration (OSC 7, OSC 133).
            "shell-integration = none",
            "confirm-close-surface = false",
            "mouse-hide-while-typing = true",
            // SwiftTerm's behaviour: Option is Meta, nothing copies on select,
            // programs may use the clipboard (OSC 52). Multi-line pastes go
            // to Wireline's confirm card (confirm_read_clipboard_cb).
            "macos-option-as-alt = true",
            "copy-on-select = false",
            "clipboard-read = allow",
            "clipboard-write = allow",
            "clipboard-paste-protection = \(PasteConfirmPolicy.current != .never)",
            "clipboard-paste-bracketed-safe = \(PasteConfirmPolicy.current == .unlessBracketed)",
            "desktop-notifications = false",
            // No Ghostty keybindings: ⌘ shortcuts belong to Wireline's menus
            // (they reach the view as menu actions — copy:, paste: …). Only
            // the scrollback keys SwiftTerm also had, which no menu uses.
            "keybind = clear",
            "keybind = shift+page_up=scroll_page_up",
            "keybind = shift+page_down=scroll_page_down",
            "keybind = shift+home=scroll_to_top",
            "keybind = shift+end=scroll_to_bottom",
        ]
        return lines.joined(separator: "\n") + "\n"
    }

    static func hex(_ c: [Double]) -> String {
        func byte(_ i: Int) -> Int { Int((min(max(i < c.count ? c[i] : 0, 0), 1) * 255).rounded()) }
        return String(format: "#%02x%02x%02x", byte(0), byte(1), byte(2))
    }

    private static func clean(_ v: CGFloat) -> String {
        v == v.rounded() ? String(Int(v)) : String(format: "%.2f", Double(v))
    }
}
